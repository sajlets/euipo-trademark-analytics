"""Render a compact KPI snapshot from the local DuckDB database."""

from __future__ import annotations

import argparse
import os
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import urlparse, urlunparse

import duckdb

from trademark_analytics.load_data import DEFAULT_DATABASE


def _markdown_table(headers: list[str], rows: list[tuple[object, ...]]) -> str:
    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    lines.extend(
        "| " + " | ".join(str(value) for value in row) + " |" for row in rows
    )
    return "\n".join(lines)


def _safe_source(source: str) -> str:
    parsed = urlparse(source)
    if parsed.scheme not in {"http", "https"}:
        return source
    host = parsed.hostname or ""
    if parsed.port:
        host = f"{host}:{parsed.port}"
    return urlunparse(parsed._replace(netloc=host, query="", fragment=""))


def build_report(database: Path, source: str, generated_at: datetime) -> str:
    if not database.is_file():
        raise FileNotFoundError(f"DuckDB database does not exist: {database}")

    with duckdb.connect(str(database), read_only=True) as connection:
        source_type, loaded_at, input_rows = connection.execute(
            "SELECT source_type, loaded_at, input_rows FROM ingestion_metadata"
        ).fetchone()
        years = connection.execute(
            """
            SELECT filing_year, application_count
            FROM kpi_filings_per_year
            ORDER BY filing_year
            """
        ).fetchall()
        estonian = connection.execute(
            """
            SELECT filing_year, estonian_application_count,
                   total_application_count, estonian_share
            FROM kpi_estonian_share
            ORDER BY filing_year
            """
        ).fetchall()
        latest_year = years[-1][0] if years else None
        if latest_year is None:
            raise ValueError("No filing-year KPIs found in the database")
        top_classes = connection.execute(
            """
            SELECT nice_class, application_count
            FROM kpi_top_nice_classes
            WHERE filing_year = ?
            ORDER BY application_count DESC, nice_class
            LIMIT 10
            """,
            [latest_year],
        ).fetchall()
        filing_types = connection.execute(
            """
            SELECT filing_type, application_count
            FROM kpi_filing_type_split
            WHERE filing_year = ?
            ORDER BY application_count DESC, filing_type
            """,
            [latest_year],
        ).fetchall()
        growth = connection.execute(
            """
            SELECT previous_year_count, yoy_growth
            FROM kpi_year_over_year_growth
            WHERE filing_year = ?
            """,
            [latest_year],
        ).fetchone()
        checks = connection.execute(
            """
            SELECT check_name, severity, issue_count
            FROM data_quality_checks
            ORDER BY CASE severity WHEN 'error' THEN 0 ELSE 1 END, check_name
            """
        ).fetchall()

    growth_count, growth_rate = growth
    growth_display = (
        "N/A (no immediately preceding calendar-year comparison)"
        if growth_rate is None
        else f"{growth_rate:+.1%} (from {growth_count:,})"
    )
    share_rows = [
        (year, f"{ee_count:,}", f"{total:,}", f"{share:.1%}")
        for year, ee_count, total, share in estonian
    ]
    check_rows = [
        (name, severity.upper(), f"{count:,}") for name, severity, count in checks
    ]
    source_display = (
        "synthetic sample data (not EUIPO observations)"
        if source_type == "synthetic_sample"
        else _safe_source(source)
    )

    return f"""<!-- Generated by trademark_analytics.publish_kpis; do not edit by hand. -->
# Latest trade mark filing KPIs

**Generated:** {generated_at.astimezone(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")}  
**Source:** `{source_display}`  
**Last loaded:** {loaded_at}  
**Input rows:** {input_rows:,}  
**Latest year in source:** {latest_year}

## Annual application volume

Application counts are distinct application numbers (not rows/classes).

{_markdown_table(["Filing year", "Applications"], years)}

## Estonian applicant share

This is the share listing Estonia as the applicant country; it does not represent
applications filed at the Estonian Patent Office.

{_markdown_table(["Filing year", "EE applications", "All applications", "EE share"], share_rows)}

## Latest year details ({latest_year})

**Year-over-year growth:** {growth_display}

### Top Nice classes

One application can be counted in multiple Nice classes.

{_markdown_table(["Nice class", "Applications"], top_classes)}

### Filing type

{_markdown_table(["Filing type", "Applications"], filing_types)}

## Data quality checks

{_markdown_table(["Check", "Severity", "Issues"], check_rows)}

See [KPI definitions](kpi_definitions.md) for metric definitions and caveats.
"""


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Write docs/latest_kpis.md from the DuckDB KPI views."
    )
    parser.add_argument("--database", type=Path, default=DEFAULT_DATABASE)
    parser.add_argument(
        "--source",
        default=os.environ.get("EUIPO_CSV_URL", "not recorded"),
        help="Dataset URL or source label recorded in the report",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "docs" / "latest_kpis.md",
    )
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        build_report(args.database, args.source, datetime.now(timezone.utc)),
        encoding="utf-8",
    )
    print(f"Updated {args.output}")


if __name__ == "__main__":
    main()
